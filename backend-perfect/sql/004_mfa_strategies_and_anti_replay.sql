-- Strategy-backed MFA persistence, anti-replay, recovery codes, and
-- concurrency-safe authentication-attempt accounting. Run after 003.
-- This migration is additive and deliberately does not change 001, 002, or 003.

-- One row per in-flight login or Step-Up request. A reservation is made before
-- password/TOTP validation, preventing a concurrent burst from bypassing the
-- shared allowance. It contains only a server-generated UUID and opaque HMAC
-- subject, never credentials, JWTs, emails, or TOTP secrets.
CREATE TABLE IF NOT EXISTS public.auth_rate_limit_reservations (
    reservation_id uuid PRIMARY KEY,
    scope text NOT NULL,
    subject_key text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT auth_rate_limit_reservations_scope_check CHECK (scope IN ('LOGIN', 'MFA')),
    CONSTRAINT auth_rate_limit_reservations_subject_key_check
        CHECK (subject_key ~ '^[0-9a-f]{64}$'),
    CONSTRAINT auth_rate_limit_reservations_state_fk
        FOREIGN KEY (scope, subject_key)
        REFERENCES public.auth_rate_limit_attempts (scope, subject_key)
        ON DELETE CASCADE
);

ALTER TABLE public.auth_rate_limit_reservations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.auth_rate_limit_reservations FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON TABLE public.auth_rate_limit_reservations TO service_role;

-- Store only the greatest successfully accepted TOTP counter. A lower or equal
-- counter is rejected, which also prevents a C-1 code from being used after C
-- or C+1 was accepted.
CREATE TABLE IF NOT EXISTS public.totp_mfa_replay_state (
    user_id uuid PRIMARY KEY REFERENCES public.app_users(id) ON DELETE CASCADE,
    last_accepted_counter bigint,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT totp_mfa_replay_state_counter_check
        CHECK (last_accepted_counter IS NULL OR last_accepted_counter >= 0)
);

ALTER TABLE public.totp_mfa_replay_state ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.totp_mfa_replay_state FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.totp_mfa_replay_state TO service_role;

-- A pre-auth JTI remains here until its JWT expiration. The backend removes
-- expired rows during subsequent confirmations; an expired token is rejected
-- cryptographically before this function is called as well.
CREATE TABLE IF NOT EXISTS public.pre_auth_token_consumptions (
    jti uuid PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pre_auth_token_consumptions_expiry_check CHECK (expires_at > consumed_at)
);

CREATE INDEX IF NOT EXISTS pre_auth_token_consumptions_expiry_idx
    ON public.pre_auth_token_consumptions (expires_at);

ALTER TABLE public.pre_auth_token_consumptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.pre_auth_token_consumptions FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON TABLE public.pre_auth_token_consumptions TO service_role;

-- Recovery codes are Argon2id hashes generated by the backend. Regeneration
-- soft-revokes active prior rows atomically, while used/revoked hashes never
-- reach a client.
CREATE TABLE IF NOT EXISTS public.backup_codes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    code_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_at timestamptz,
    revoked_at timestamptz,
    CONSTRAINT backup_codes_hash_check CHECK (length(code_hash) > 0),
    CONSTRAINT backup_codes_terminal_state_check CHECK (
        NOT (used_at IS NOT NULL AND revoked_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS backup_codes_active_by_user_idx
    ON public.backup_codes (user_id)
    WHERE used_at IS NULL AND revoked_at IS NULL;

ALTER TABLE public.backup_codes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.backup_codes FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.backup_codes TO service_role;

-- Reserve exactly one allowed authentication attempt while holding the state
-- row lock. The fifth reservation begins the lock immediately; if it succeeds,
-- only that request's completion restores one slot.
CREATE OR REPLACE FUNCTION public.reserve_auth_rate_limit_attempt(
    p_scope text,
    p_subject_key text,
    p_reservation_id uuid,
    p_max_attempts integer,
    p_lock_seconds integer
)
RETURNS TABLE (allowed boolean, reservation_id uuid, locked_until timestamptz)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    attempt_state public.auth_rate_limit_attempts%ROWTYPE;
    current_time timestamptz := clock_timestamp();
    new_locked_until timestamptz;
BEGIN
    IF p_scope NOT IN ('LOGIN', 'MFA')
       OR p_subject_key !~ '^[0-9a-f]{64}$'
       OR p_reservation_id IS NULL
       OR p_max_attempts NOT BETWEEN 1 AND 20
       OR p_lock_seconds NOT BETWEEN 60 AND 86400 THEN
        RAISE EXCEPTION 'Invalid authentication rate-limit input';
    END IF;

    INSERT INTO public.auth_rate_limit_attempts (scope, subject_key)
    VALUES (p_scope, p_subject_key)
    ON CONFLICT (scope, subject_key) DO NOTHING;

    SELECT * INTO attempt_state
    FROM public.auth_rate_limit_attempts
    WHERE scope = p_scope AND subject_key = p_subject_key
    FOR UPDATE;

    IF attempt_state.locked_until IS NOT NULL
       AND attempt_state.locked_until > current_time THEN
        RETURN QUERY SELECT false, NULL::uuid, attempt_state.locked_until;
        RETURN;
    END IF;

    IF attempt_state.locked_until IS NOT NULL THEN
        -- An old request that outlived the lock cannot alter the next window.
        DELETE FROM public.auth_rate_limit_reservations
        WHERE scope = p_scope AND subject_key = p_subject_key;
        attempt_state.attempt_count := 0;
    END IF;

    IF attempt_state.attempt_count >= p_max_attempts THEN
        new_locked_until := current_time + make_interval(secs => p_lock_seconds);
        UPDATE public.auth_rate_limit_attempts
        SET locked_until = new_locked_until, updated_at = current_time
        WHERE scope = p_scope AND subject_key = p_subject_key;
        RETURN QUERY SELECT false, NULL::uuid, new_locked_until;
        RETURN;
    END IF;

    IF attempt_state.attempt_count + 1 = p_max_attempts THEN
        new_locked_until := current_time + make_interval(secs => p_lock_seconds);
    ELSE
        new_locked_until := NULL;
    END IF;

    UPDATE public.auth_rate_limit_attempts
    SET attempt_count = attempt_state.attempt_count + 1,
        locked_until = new_locked_until,
        updated_at = current_time
    WHERE scope = p_scope AND subject_key = p_subject_key;

    INSERT INTO public.auth_rate_limit_reservations (reservation_id, scope, subject_key)
    VALUES (p_reservation_id, p_scope, p_subject_key);

    RETURN QUERY SELECT true, p_reservation_id, NULL::timestamptz;
END;
$$;

-- Finalize one exact request receipt. A failure keeps the reserved count;
-- success decrements only its own receipt, never a concurrent attempt.
CREATE OR REPLACE FUNCTION public.complete_auth_rate_limit_attempt(
    p_reservation_id uuid,
    p_succeeded boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    reservation_state public.auth_rate_limit_reservations%ROWTYPE;
    attempt_state public.auth_rate_limit_attempts%ROWTYPE;
    current_time timestamptz := clock_timestamp();
BEGIN
    IF p_reservation_id IS NULL OR p_succeeded IS NULL THEN
        RAISE EXCEPTION 'Invalid authentication rate-limit input';
    END IF;

    SELECT * INTO reservation_state
    FROM public.auth_rate_limit_reservations
    WHERE reservation_id = p_reservation_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT * INTO attempt_state
    FROM public.auth_rate_limit_attempts
    WHERE scope = reservation_state.scope
      AND subject_key = reservation_state.subject_key
    FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    DELETE FROM public.auth_rate_limit_reservations
    WHERE reservation_id = p_reservation_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    IF p_succeeded THEN
        UPDATE public.auth_rate_limit_attempts
        SET attempt_count = GREATEST(attempt_state.attempt_count - 1, 0),
            locked_until = NULL,
            updated_at = current_time
        WHERE scope = reservation_state.scope
          AND subject_key = reservation_state.subject_key;
    END IF;
END;
$$;

-- Regenerate a bounded set of recovery-code hashes as one transaction. Only
-- active unused codes are revoked; consumed rows remain as an audit trail.
CREATE OR REPLACE FUNCTION public.replace_backup_codes(
    p_user_id uuid,
    p_code_hashes text[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    current_time timestamptz := clock_timestamp();
BEGIN
    IF p_user_id IS NULL
       OR cardinality(p_code_hashes) NOT BETWEEN 1 AND 10
       OR EXISTS (
            SELECT 1 FROM unnest(p_code_hashes) AS code_hash
            WHERE code_hash IS NULL OR length(code_hash) = 0
       ) THEN
        RAISE EXCEPTION 'Invalid backup-code replacement input';
    END IF;

    -- Serialize concurrent regenerations for this account. Each subsequent
    -- transaction sees and revokes the active set produced by its predecessor.
    PERFORM 1
    FROM public.app_users
    WHERE id = p_user_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown backup-code account';
    END IF;

    UPDATE public.backup_codes
    SET revoked_at = current_time
    WHERE user_id = p_user_id
      AND used_at IS NULL
      AND revoked_at IS NULL;

    INSERT INTO public.backup_codes (user_id, code_hash)
    SELECT p_user_id, code_hash
    FROM unnest(p_code_hashes) AS code_hash;
END;
$$;

-- Confirm one factor and consume the pre-auth JTI in the same transaction.
-- The JTI insert happens only after the factor's freshness/availability check,
-- so an invalid code, replayed TOTP counter, or used recovery code does not
-- burn a still-valid pre-auth token.
CREATE OR REPLACE FUNCTION public.confirm_mfa_step_up(
    p_user_id uuid,
    p_pre_auth_jti uuid,
    p_pre_auth_expires_at timestamptz,
    p_method text,
    p_totp_counter bigint,
    p_backup_code_id uuid
)
RETURNS TABLE (confirmed boolean)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    replay_state public.totp_mfa_replay_state%ROWTYPE;
    backup_code public.backup_codes%ROWTYPE;
    current_time timestamptz := clock_timestamp();
BEGIN
    IF p_user_id IS NULL
       OR p_pre_auth_jti IS NULL
       OR p_pre_auth_expires_at IS NULL
       OR p_pre_auth_expires_at <= current_time
       OR p_method NOT IN ('totp', 'backup_code') THEN
        RETURN QUERY SELECT false;
        RETURN;
    END IF;

    -- Never delete a consumed JTI before its own token expiry.
    DELETE FROM public.pre_auth_token_consumptions
    WHERE expires_at <= current_time;

    IF p_method = 'totp' THEN
        IF p_totp_counter IS NULL OR p_totp_counter < 0 OR p_backup_code_id IS NOT NULL THEN
            RETURN QUERY SELECT false;
            RETURN;
        END IF;

        INSERT INTO public.totp_mfa_replay_state (user_id, last_accepted_counter)
        VALUES (p_user_id, NULL)
        ON CONFLICT (user_id) DO NOTHING;

        SELECT * INTO replay_state
        FROM public.totp_mfa_replay_state
        WHERE user_id = p_user_id
        FOR UPDATE;

        IF replay_state.last_accepted_counter IS NOT NULL
           AND p_totp_counter <= replay_state.last_accepted_counter THEN
            RETURN QUERY SELECT false;
            RETURN;
        END IF;

        INSERT INTO public.pre_auth_token_consumptions (jti, user_id, expires_at)
        VALUES (p_pre_auth_jti, p_user_id, p_pre_auth_expires_at)
        ON CONFLICT (jti) DO NOTHING;
        IF NOT FOUND THEN
            RETURN QUERY SELECT false;
            RETURN;
        END IF;

        UPDATE public.totp_mfa_replay_state
        SET last_accepted_counter = p_totp_counter,
            updated_at = current_time
        WHERE user_id = p_user_id;

        RETURN QUERY SELECT true;
        RETURN;
    END IF;

    IF p_backup_code_id IS NULL OR p_totp_counter IS NOT NULL THEN
        RETURN QUERY SELECT false;
        RETURN;
    END IF;

    SELECT * INTO backup_code
    FROM public.backup_codes
    WHERE id = p_backup_code_id
      AND user_id = p_user_id
      AND used_at IS NULL
      AND revoked_at IS NULL
    FOR UPDATE;
    IF NOT FOUND THEN
        RETURN QUERY SELECT false;
        RETURN;
    END IF;

    INSERT INTO public.pre_auth_token_consumptions (jti, user_id, expires_at)
    VALUES (p_pre_auth_jti, p_user_id, p_pre_auth_expires_at)
    ON CONFLICT (jti) DO NOTHING;
    IF NOT FOUND THEN
        RETURN QUERY SELECT false;
        RETURN;
    END IF;

    UPDATE public.backup_codes
    SET used_at = current_time
    WHERE id = backup_code.id;

    RETURN QUERY SELECT true;
END;
$$;

